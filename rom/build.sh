#!/usr/bin/env bash
# rom/build.sh : test.s -> test.sms, boot.s (includes it) -> rom.hex and src/board/rom_cfg.vh
set -euo pipefail
cd "$(dirname "$0")"
python make_data.py
python ../tools/z80asm.py test.s test.sms 8192
python ../tools/z80asm.py boot.s boot.bin 16384
python -c "
d=open('boot.bin','rb').read()
open('rom.hex','w',newline='\n').write('\n'.join('%02x'%x for x in d)+'\n')
"
printf '// generated by rom/build.sh\n`define ROM_HEX "%s/rom.hex"\n' "$(pwd -W)" > ../src/board/rom_cfg.vh
