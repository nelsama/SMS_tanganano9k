#!/usr/bin/env bash
# menu/build.sh : menu.c -> menu.hex + src/board/rom_cfg.vh (SDCC)
set -euo pipefail
cd "$(dirname "$0")"; export PATH="${SDCC:-/c/Program Files/SDCC/bin}:$PATH"; O=../build/menu; mkdir -p $O
python make_font.py $O/font.c
cp crt0.s $O/crt0.s; (cd $O; sdasz80 -o crt0.rel crt0.s)
for f in menu.c fat.c $O/font.c; do
  sdcc -mz80 --std-c11 --opt-code-size --max-allocs-per-node 20000 -c -o $O/$(basename $f .c).rel $f
done
sdcc -mz80 --no-std-crt0 --code-loc 0x0070 --data-loc 0xD280 -o $O/menu.ihx $O/crt0.rel $O/menu.rel $O/fat.rel $O/font.rel
python - "$O" <<'E'
import sys
O = sys.argv[1]; m = bytearray(b'\xff' * 16384); end = 0
for l in open(O + '/menu.ihx'):
    b = bytes.fromhex(l.strip()[1:])
    if b[3] == 0:
        a = b[1] << 8 | b[2]; assert a + b[0] <= 16384, 'menu too big'
        m[a:a + b[0]] = b[4:4 + b[0]]; end = max(end, a + b[0])
open('menu.hex', 'w', newline='\n').write('\n'.join('%02x' % x for x in m) + '\n')
print('menu: %d of 16384 bytes' % end)
E
printf '// generated by menu/build.sh\n`define ROM_HEX "%s/menu.hex"\n' "$(pwd -W)" > ../src/board/rom_cfg.vh
grep -E '^(_DATA|_BSS|_INITIALIZED|_INITIALIZER|_CODE) ' $O/menu.map
